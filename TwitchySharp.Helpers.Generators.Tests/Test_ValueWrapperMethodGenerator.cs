    [Fact]
    public async Task Generator_AddsAllMembers_ToPartialWrapperStruct()
    {
        const string TEST_SOURCE = """
            using TwitchySharp.Helpers;
            using System.Text.Json.Serialization;

            namespace TestNamespace;
            /// <summary>Test type</summary>
            public partial struct TestWrapper : IWrapValue<string>;
            """;

        const string EXPECTED_GENERATED_SOURCE = """
            // <auto-generated/>
            #nullable enable

            namespace TestNamespace;

            [global::System.Text.Json.Serialization.JsonConverter(typeof(TestWrapperJsonConverter))]
            public partial struct TestWrapper
            {
                public required string Value { get; init; }
                public static implicit operator string(TestWrapper wrapper) => wrapper.Value;
                public override global::System.String ToString() => Value?.ToString() ?? global::System.String.Empty;
                private class TestWrapperJsonConverter : global::System.Text.Json.Serialization.JsonConverter<TestWrapper>
                {
                    public override TestWrapper Read(ref global::System.Text.Json.Utf8JsonReader reader, global::System.Type typeToConvert, global::System.Text.Json.JsonSerializerOptions options)
                    {
                        if (global::System.Text.Json.JsonSerializer.Deserialize<string>(ref reader, options) is not string value)
                            return default;
                        return new TestWrapper { Value = value };
                    }
                    public override void Write(global::System.Text.Json.Utf8JsonWriter writer, TestWrapper value, global::System.Text.Json.JsonSerializerOptions options)
                    {
                        global::System.Text.Json.JsonSerializer.Serialize(writer, value.Value, options);
                    }
                }
            }

            """;

        CSharpSourceGeneratorTest<ValueWrapperMethodGenerator, DefaultVerifier> test = CreateGeneratorTest(TEST_SOURCE);
        test.TestState.GeneratedSources.Add((typeof(ValueWrapperMethodGenerator), "TestWrapper_ConversionMethods.g.cs", EXPECTED_GENERATED_SOURCE));

        await test.RunAsync(TestContext.Current.CancellationToken);
    }

