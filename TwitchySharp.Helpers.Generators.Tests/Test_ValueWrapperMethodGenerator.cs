namespace TwitchySharp.Helpers.Generators.Tests;

public class Test_ValueWrapperMethodGenerator
{
    private const string FAKE_CONVERTER = """
        using System;
        using System.Text.Json;
        using System.Text.Json.Serialization;

        namespace TestNamespace;
        public class FakeConverter<T> : JsonConverter<T>
        {
            public override T? Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)
            {
                throw new NotImplementedException();
            }
            public override void Write(Utf8JsonWriter writer, T value, JsonSerializerOptions options)
            {
                throw new NotImplementedException();
            }
        }

        """;

    private static CSharpSourceGeneratorTest<ValueWrapperMethodGenerator, DefaultVerifier> CreateGeneratorTest(string input)
    {
        CSharpSourceGeneratorTest<ValueWrapperMethodGenerator, DefaultVerifier> test = new()
        {
            TestCode = input,
            ReferenceAssemblies = ReferenceAssemblies.Net.Net80
        };
        test.TestState.AdditionalReferences.Add(typeof(IWrapValue<>).Assembly);
        test.TestState.Sources.Add(FAKE_CONVERTER);
        return test;
    }

    [Fact]
    public async Task Generator_AddsValueProperty_ToPartialWrapperStruct()
    {
        const string TEST_SOURCE = $$"""
            using TwitchySharp.Helpers;
            using System.Text.Json.Serialization;

            namespace TestNamespace;
            /// <summary>Test type</summary>
            [JsonConverter(typeof(FakeConverter<TestWrapper>))]
            public readonly partial record struct TestWrapper : IWrapValue<string>
            {
                public static implicit operator string(TestWrapper wrapper) => wrapper.Value;
                public override string ToString() => Value.ToString();
            }
            """;

        const string EXPECTED_GENERATED_SOURCE = """
            // <auto-generated/>
            #nullable enable

            namespace TestNamespace;

            public readonly partial record struct TestWrapper
            {
                public required string Value { get; init; }
            }

            """;

        CSharpSourceGeneratorTest<ValueWrapperMethodGenerator, DefaultVerifier> test = CreateGeneratorTest(TEST_SOURCE);
        test.TestState.GeneratedSources.Add((typeof(ValueWrapperMethodGenerator), "TestWrapper_ConversionMethods.g.cs", EXPECTED_GENERATED_SOURCE));

        await test.RunAsync(TestContext.Current.CancellationToken);
    }

