using System.Collections.Immutable;
using TwitchySharp.Infrastructure.Functional;

namespace TwitchySharp.Api.Helix.EventSub.Subscriptions;
/// <summary>
/// Get notified when progress (either positive or negative) is made towards a broadcaster's goal.
/// Note that it is possible to receive this event before receiving a <see cref="GoalBegin"/> event.
/// </summary>
/// <remarks>
/// Requires a user access token that includes <see cref="Scope.ChannelReadGoals"/>.
/// </remarks>
/// <param name="BroadcasterUserId">
/// The user id of the broadcaster to get notified about.
/// This user must have created a user access token for this application that includes <see cref="Scope.ChannelReadGoals"/>.
/// </param>
public sealed record GoalProgress(UserId BroadcasterUserId)
    : EventSubSubscriptionTypeSpecification, IConditionConstructable<GoalProgress>
{
    public override EventSubSubscriptionType Type => EventSubSubscriptionType.GoalProgress;
    public static EventSubSubscriptionType SubscriptionType => EventSubSubscriptionType.GoalProgress;
    public override EventSubSubscriptionAuthenticationContext.UserAuthorized AuthenticationContext
        => new()
        {
            Identity = new TwitchIdentity.User(BroadcasterUserId),
            ValidScopes = ImmutableHashSet.Create(Scope.ChannelReadGoals)
        };

    public override IReadOnlyDictionary<ConditionKey, object> Condition { get; }
        = new EventSubSubscriptionCondition()
            .Set(new("broadcaster_user_id"), BroadcasterUserId);
    public static Validation<GoalProgress> FromCondition(IReadOnlyDictionary<ConditionKey, string> condition)
        => condition
            .GetRequiredValue(new("broadcaster_user_id"), out UserId BroadcasterUserId, value => new(value))
            .Map(_ => new GoalProgress(BroadcasterUserId));
}
