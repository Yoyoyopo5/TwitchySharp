using Microsoft.IdentityModel.JsonWebTokens;
using Yoyoyopo5.ValueWrapper;

namespace TwitchySharp.Api;

/// <summary>
/// A Twitch API bearer access token.
/// </summary>
/// <remarks>
/// Use <see cref="AppAccessToken"/>, <see cref="ExtensionJsonWebToken"/>, or <see cref="UserAccessToken"/>, depending on the endpoint.
/// </remarks>
public interface IAccessToken
{
    /// <summary>
    /// The string value of the access token.
    /// </summary>
    string Value { get; }
}

/// <summary>
/// A bearer token used in the <c>Authorization</c> HTTP header.
/// </summary>
/// <param name="Value">The string value of the token.</param>
[Wrapper<string>]
public readonly partial record struct BearerToken(string Value);

// Below can likely move to Api.Authentication

/// <summary>
/// A Twitch app access token.
/// </summary>
/// <remarks>
/// APIs that don’t require the user’s permission to access resources use app access tokens.
/// <br/>
/// See <see href="https://dev.twitch.tv/docs/authentication/#app-access-tokens">App Access Tokens</see> for more information.
/// </remarks>
[Wrapper<string>]
public readonly partial record struct AppAccessToken(string Value) : IAccessToken
{
    /// <summary>
    /// Convert to <see cref="BearerToken"/>.
    /// </summary>
    /// <param name="token">The app access token to use as a bearer token.</param>
    public static implicit operator BearerToken(AppAccessToken token) => new(token.Value);
}

/// <summary>
/// A Twitch user access token.
/// </summary>
/// <remarks>
/// APIs that require the user’s permission to access resources use user access tokens. Can include various <see cref="Scope"/>s.
/// <br/>
/// See <see href="https://dev.twitch.tv/docs/authentication/#user-access-tokens">User Access Tokens</see> for more information.
/// </remarks>
[Wrapper<string>]
public readonly partial record struct UserAccessToken(string Value) : IAccessToken
{
    /// <summary>
    /// Convert to <see cref="BearerToken"/>.
    /// </summary>
    /// <param name="token">The user access token to use as a bearer token.</param>
    public static implicit operator BearerToken(UserAccessToken token) => new(token.Value);
}

/// <summary>
/// A Twitch extension JSON web token generated by an EBS.
/// </summary>
/// <remarks>
/// See <see href="https://dev.twitch.tv/docs/extensions/building/#signing-the-jwt">Signing the JWT</see> for more information.
/// </remarks>
[Wrapper<string>]
public readonly partial record struct ExtensionJsonWebToken(string Value) : IAccessToken
{
    /// <summary>
    /// Convert to <see cref="BearerToken"/>.
    /// </summary>
    /// <param name="jwt">The extension JWT to use as a bearer token.</param>
    public static implicit operator BearerToken(ExtensionJsonWebToken jwt) => new(jwt.Value);
}

/// <summary>
/// Extension class for <see cref="ToJsonWebToken(ExtensionJsonWebToken)"/>.
/// </summary>
public static class ExtensionJsonWebTokenJwtExtension
{
    /// <summary>
    /// Read an <see cref="ExtensionJsonWebToken"/> as a <see cref="JsonWebToken"/>.
    /// </summary>
    /// <remarks>
    /// Note that this does not validate the JWT or decrypt the payload if it is encrypted.
    /// </remarks>
    /// <param name="extensionJwt"></param>
    /// <returns></returns>
    public static JsonWebToken ToJsonWebToken(this ExtensionJsonWebToken extensionJwt)
        => new JsonWebTokenHandler().ReadJsonWebToken(extensionJwt.Value);
}
